// Token and component exports for developers.
import { meshFill } from './snippet.js';

const cssName = (k) => `--${k}`;

function resolve(kit, value, seen = new Set()) {
  if (typeof value === 'string' && value.startsWith('$')) {
    const key = value.slice(1);
    if (seen.has(key) || !kit.tokens[key]) return value;
    seen.add(key);
    return resolve(kit, kit.tokens[key].value, seen);
  }
  return value;
}

function cssValue(kit, name, t) {
  const v = resolve(kit, t.value);
  if (t.type === 'number') {
    if (/^ds-(fs|r|s|h|w|pad|gap|icon|bw)/.test(name) || /^ds-r-/.test(name)) return name === 'ds-r-pill' ? '9999px' : `${v}px`;
    return String(v);
  }
  if (t.type === 'string') return name === 'ds-font' ? `"${v}", ui-sans-serif, system-ui, sans-serif` : `"${v}"`;
  return v;
}

export function glowBackground(g) {
  const [a, b, c, d, e, f, , h] = g.colors;
  return [
    `radial-gradient(60% 70% at ${g.center[0] * 100}% ${g.center[1] * 100}%, ${e} 0%, transparent 70%)`,
    `radial-gradient(50% 60% at 0% 0%, ${a} 0%, transparent 70%)`,
    `radial-gradient(50% 60% at 100% 0%, ${c} 0%, transparent 70%)`,
    `radial-gradient(60% 60% at 100% 100%, ${f} 0%, transparent 70%)`,
    `linear-gradient(135deg, ${b}, ${d} 50%, ${h})`,
  ].join(', ');
}

export function tokensCss(kit) {
  const lines = ['/* opencv design tokens. Generated by opencv-kit from opencv.pen. */', ':root {'];
  for (const [k, t] of Object.entries(kit.tokens)) {
    if (typeof t.value === 'object') continue;
    lines.push(`  ${cssName(k)}: ${cssValue(kit, k, t)};`);
  }
  lines.push('}', '');
  for (const [name, g] of Object.entries(kit.glow)) {
    lines.push(`/* ${g.use} */`, `.glow-${name} {`, `  background: ${glowBackground(g)};`, '}', '');
  }
  lines.push('/* Primary button: the glow, never black. */', '.btn-primary {', `  background: ${glowBackground(kit.glow.button)};`, '  color: #1B1B1F;', '  box-shadow: inset 0 0 0 1px rgb(255 255 255 / 0.7), 0 2px 10px rgb(142 164 224 / 0.3);', '}', '');
  return lines.join('\n');
}

export function tailwindPreset(kit) {
  const colors = {};
  const radius = {};
  const spacing = {};
  const fontSize = {};
  for (const [k, t] of Object.entries(kit.tokens)) {
    if (!k.startsWith('ds-') || typeof t.value === 'object') continue;
    const key = k.slice(3);
    if (t.type === 'color') colors[key] = `var(--${k})`;
    else if (k.startsWith('ds-r-')) radius[key.slice(2)] = `var(--${k})`;
    else if (k.startsWith('ds-s-')) spacing[key] = `var(--${k})`;
    else if (k.startsWith('ds-fs-')) fontSize[key.slice(3)] = `var(--${k})`;
  }
  return `// opencv Tailwind preset. Import tokens.css once, then: presets: [require('./opencv.preset.cjs')]
module.exports = {
  theme: {
    extend: {
      colors: ${JSON.stringify(colors, null, 6).replace(/\n}/, '\n      }')},
      borderRadius: ${JSON.stringify(radius, null, 6).replace(/\n}/, '\n      }')},
      spacing: ${JSON.stringify(spacing, null, 6).replace(/\n}/, '\n      }')},
      fontSize: ${JSON.stringify(fontSize, null, 6).replace(/\n}/, '\n      }')},
      fontFamily: { sans: ['Inter', 'ui-sans-serif', 'system-ui', 'sans-serif'] },
    },
  },
};
`;
}

export function tokensW3c(kit) {
  const out = { $description: 'opencv design tokens (W3C design tokens format)' };
  for (const [k, t] of Object.entries(kit.tokens)) {
    if (typeof t.value === 'object') continue;
    const [group] = k.split('-');
    out[group] ??= {};
    const v = t.value;
    out[group][k] = {
      $type: t.type === 'color' ? 'color' : t.type === 'number' ? 'dimension' : 'string',
      $value: typeof v === 'string' && v.startsWith('$') ? `{${v.slice(1).split('-')[0]}.${v.slice(1)}}` : t.type === 'number' ? `${v}px` : v,
    };
  }
  out.glow = Object.fromEntries(Object.entries(kit.glow).map(([n, g]) => [n, { $type: 'other', $description: g.use, $value: meshFill(g) }]));
  return out;
}

export function componentsManifest(kit) {
  return {
    source: kit.source,
    generatedAt: kit.generatedAt,
    components: kit.components.map((c) => ({
      key: c.key, name: c.name, kind: c.kind, description: c.desc, spec: c.spec,
      variants: c.variants.map((v) => ({ id: v.id, name: v.name, parts: v.parts, slots: v.texts.map((t) => t.name || t.content) })),
    })),
    deprecated: kit.deprecated,
  };
}
