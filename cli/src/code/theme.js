// Builds opencv.css (Tailwind v4 theme) from the kit tokens, so the code always matches opencv.pen.
import { glowBackground } from '../export.js';

// Tailwind theme name -> kit token.
export const COLOR_MAP = {
  sidebar: 'ds-bg-sidebar', canvas: 'ds-bg-canvas', surface: 'ds-bg-surface', hover: 'ds-bg-hover', active: 'ds-bg-active',
  subtle: 'ds-bg-subtle', chip: 'ds-bg-chip', 'block-hover': 'ds-bg-block-hover', selection: 'ds-selection',
  border: 'ds-border', 'border-strong': 'ds-border-strong',
  fg: 'ds-text-primary', 'fg-2': 'ds-text-secondary', 'fg-3': 'ds-text-tertiary', placeholder: 'ds-text-placeholder',
  success: 'ds-success', 'success-soft': 'ds-success-soft', danger: 'ds-danger', 'danger-soft': 'ds-danger-soft',
  info: 'ds-info', 'info-soft': 'ds-info-soft', warning: 'ds-warning', 'warning-soft': 'ds-warning-soft',
  focus: 'ds-focus', indigo: 'ds-label-indigo',
  'stage-saved': 'ds-stage-saved', 'stage-applied': 'ds-stage-applied', 'stage-interview': 'ds-stage-interview',
  'stage-offer': 'ds-stage-offer', 'stage-closed': 'ds-stage-closed',
  'site-bg': 'l-bg', 'site-surface': 'l-surface', 'site-panel': 'l-panel', 'site-line': 'l-line',
  'site-text': 'l-text', 'site-muted': 'l-muted', 'site-faint': 'l-faint',
};

const FALLBACK = {
  'ds-bg-block-hover': '#F6F6F7', 'ds-selection': '#DCDCE0', 'ds-focus': '#6D78D5', 'ds-success-soft': '#E4F4EC',
  'ds-danger-soft': '#FCE9E9', 'ds-info-soft': '#E6ECFF', 'ds-warning-soft': '#F8F0D0', 'ds-bg-subtle': '#F4F4F5',
};

function value(kit, key, seen = new Set()) {
  const t = kit.tokens[key];
  if (!t) return FALLBACK[key];
  const v = t.value;
  if (typeof v === 'string' && v.startsWith('$') && !seen.has(v)) { seen.add(v); return value(kit, v.slice(1), seen); }
  return v;
}

export function themeCss(kit) {
  const colors = Object.entries(COLOR_MAP)
    .map(([name, key]) => [name, value(kit, key)])
    .filter(([, v]) => typeof v === 'string');
  const glows = Object.entries(kit.glow)
    .map(([name, g]) => `@utility glow-${name} {\n  background: ${glowBackground(g)};\n}`)
    .join('\n\n');

  return `/* opencv theme for Tailwind CSS v4. Generated by opencv-kit from opencv.pen. Do not edit by hand:
   run \`opencv init --force\` after \`opencv pen sync\` to refresh. */
@import "tailwindcss";

@theme {
  --font-sans: "Inter Variable", "Inter", ui-sans-serif, system-ui, sans-serif;
  --font-mono: "JetBrains Mono", ui-monospace, SFMono-Regular, Menlo, monospace;

${colors.map(([n, v]) => `  --color-${n}: ${v};`).join('\n')}

  --text-caption: 11px;
  --text-small: 12px;
  --text-body: 13px;
  --text-title: 15px;
  --text-h2: 20px;
  --text-page: 24px;

  --radius-chip: 4px;
  --radius-row: 6px;
  --radius-btn: 7px;
  --radius-tile: 8px;
  --radius-card: 10px;
  --radius-panel: 12px;
  --radius-media: 16px;
  --radius-site: 24px;

  --shadow-pop: 0 8px 24px rgb(0 0 0 / 0.12);
  --shadow-dialog: 0 16px 48px rgb(0 0 0 / 0.15);
  --shadow-glow: 0 2px 10px rgb(142 164 224 / 0.3);
  --shadow-glow-lg: 0 4px 14px rgb(142 164 224 / 0.4);
  --shadow-shot: 0 24px 64px rgb(27 31 46 / 0.18);
}

${glows}

/* Visible focus for keyboard users: 2px ds-focus outside the control. */
@utility focus-ring {
  outline: 2px solid var(--color-focus);
  outline-offset: 2px;
}

@layer base {
  html {
    -webkit-font-smoothing: antialiased;
    font-feature-settings: "cv11", "ss01";
  }
  body {
    @apply bg-sidebar font-sans text-body text-fg;
  }
  :focus-visible {
    outline: 2px solid var(--color-focus);
    outline-offset: 2px;
  }
  ::placeholder {
    color: var(--color-placeholder);
  }
}
`;
}
