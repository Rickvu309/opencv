import { execFileSync } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { LEDGER } from "./guard-ledger.mjs"
import { FAST_GUARDS } from "./ocv-tools/jobs/push-checks.mjs"

export const root = path.resolve(
  fileURLToPath(new URL(".", import.meta.url)),
  ".."
)
export const CHECKS_DOC = "docs/agents/checks.md"
export const FIX = "node scripts/list-checks.mjs"

export const GROUPS = Object.freeze([
  { dir: "scripts", match: /^scripts\/[^/]+\.test\.mjs$/ },
  { dir: "packages/guards", match: /^packages\/guards\/[^/]+\.test\.mjs$/ },
  {
    dir: "apps/web/src/test",
    match: /^apps\/web\/src\/test\/[^/]+\.test\.tsx?$/,
  },
  {
    dir: "apps/api/src",
    match:
      /^apps\/api\/src\/(?:registry\/[^/]+|[^/]+\/[^/]+-contract)\.test\.ts$/,
  },
])

const TOP_LEVEL_NAME = (call) =>
  new RegExp(
    `^${call}(?:\\.\\w+)?\\(\\s*(["'\`])((?:(?!\\1)[^\\\\\\n]|\\\\.)*)\\1`,
    "m"
  )

export function describeCheck(source) {
  const found =
    TOP_LEVEL_NAME("describe").exec(source) ??
    TOP_LEVEL_NAME("(?:test|it)").exec(source)
  return found ? found[2].replace(/\\(["'`])/g, "$1").trim() : null
}

export function listGuardFiles(
  list = () =>
    execFileSync(
      "git",
      ["ls-files", "--cached", "--others", "--exclude-standard"],
      {
        cwd: root,
        encoding: "utf8",
      }
    )
) {
  return list()
    .split("\n")
    .filter((file) => GROUPS.some(({ match }) => match.test(file)))
    .sort()
}

export function renderChecks({
  files = listGuardFiles(),
  read = (file) => readFileSync(path.join(root, file), "utf8"),
  fast = FAST_GUARDS,
  proven = LEDGER.filter((row) => row.historic).map((row) => row.file),
} = {}) {
  const out = [
    "# Checks",
    "",
    `Generated by \`${FIX}\` from the top-level describe or test name of each guard. A stale list fails \`scripts/checks-doc.test.mjs\`; rerun the script to fix it.`,
    "",
    "`push` runs on changed files at git push; every check runs in CI.",
    "",
    "A guard marked proven has a row in `scripts/guard-ledger.mjs` showing it fires on a real past mistake and stays quiet on the fix; rerun a proof with `node scripts/guard-ledger.mjs prove <id>`. A new guard needs a row there, or `scripts/guard-ledger.test.mjs` fails.",
  ]
  for (const { dir, match } of GROUPS) {
    const rows = files.filter((file) => match.test(file))
    if (rows.length === 0) continue
    out.push("", `## ${dir}`, "")
    for (const file of rows) {
      const name = describeCheck(read(file))
      if (name === null) throw new Error(`${file} has no top-level test name`)
      const gate = fast.includes(file) ? "push, CI" : "CI"
      const mark = proven.includes(file) ? ", proven" : ""
      out.push(
        `- \`${path.posix.relative(dir, file)}\` (${gate}${mark}): ${name}`
      )
    }
  }
  return `${out.join("\n")}\n`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = renderChecks()
  const file = path.join(root, CHECKS_DOC)
  const current = (() => {
    try {
      return readFileSync(file, "utf8")
    } catch {
      return ""
    }
  })()
  if (process.argv.includes("--check")) {
    if (current !== next) {
      console.error(`${CHECKS_DOC} is stale. Run: ${FIX}`)
      process.exit(1)
    }
  } else {
    writeFileSync(file, next)
  }
}
