import { execFileSync } from "node:child_process"
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import ts from "typescript"

export const root = path.resolve(
  fileURLToPath(new URL(".", import.meta.url)),
  ".."
)
export const BASELINE_PATH = "scripts/no-comments.baseline.json"
export const SOURCE_FILE = /\.(?:[cm]?[jt]s|[jt]sx)$/
export const CSS_FILE = /\.css$/

export const EXCLUDED = [
  { path: /\.d\.ts$/, why: "type declarations are emitted, not authored" },
  { path: /(?:^|\/)dist\//, why: "build output" },
  {
    first: /^\/\/ Generated by scripts\/\S+ from .+ Do not edit by hand\.$/,
    why: "regenerated by the script the header names",
  },
]

export const REFUSAL =
  "Comments are banned. Explain with a better name or a test. See CODING_STANDARDS.md."

const ESLINT_DIRECTIVE = /^eslint-(?:disable|enable)(?:-next-line|-line)?\b/
const TOOL_DIRECTIVES = [
  /^@ts-expect-error\b/,
  /^prettier-ignore\b/,
  /^@vitest-environment\b/,
]

function commentBody(raw) {
  if (raw.startsWith("//")) return raw.slice(2).replace(/^\//, "").trim()
  return raw
    .slice(2, -2)
    .replace(/^\*/, "")
    .replace(/\s*\*\s*$/, "")
    .trim()
}

export function isDirective(raw) {
  if (/^\/\/\/\s*<reference\s/.test(raw)) return true
  const body = commentBody(raw)
  if (ESLINT_DIRECTIVE.test(body)) {
    return /^eslint-enable\b/.test(body) || /\s--\s+\S/.test(body)
  }
  return TOOL_DIRECTIVES.some((directive) => directive.test(body))
}

function lineOf(text, offset) {
  let line = 1
  for (let i = 0; i < offset; i++) if (text.charCodeAt(i) === 10) line++
  return line
}

function makeComment(text, pos, end) {
  const raw = text.slice(pos, end)
  const line = lineOf(text, pos)
  return { line, lines: raw.split("\n").length, raw, pos, end }
}

function scriptKind(file) {
  if (/\.tsx$/.test(file)) return ts.ScriptKind.TSX
  if (/\.[cm]?ts$/.test(file)) return ts.ScriptKind.TS
  return ts.ScriptKind.JSX
}

const CSS_MARKED_NAME = /^(?:css|styles)$|(?:Css|Styles)$/

function templatePieces(template, sourceFile) {
  const tokens =
    template.kind === ts.SyntaxKind.TemplateExpression
      ? [template.head, ...template.templateSpans.map((span) => span.literal)]
      : [template]
  return tokens.map((token) => {
    const closesWithHole =
      token.kind === ts.SyntaxKind.TemplateHead ||
      token.kind === ts.SyntaxKind.TemplateMiddle
    return {
      start: token.getStart(sourceFile) + 1,
      end: token.end - (closesWithHole ? 2 : 1),
    }
  })
}

function bindingName(node) {
  if (
    ts.isVariableDeclaration(node) ||
    ts.isPropertyAssignment(node) ||
    ts.isPropertyDeclaration(node)
  )
    return ts.isIdentifier(node.name) ? node.name.text : null
  return null
}

function isStyleElementChild(node) {
  const slot = node.parent
  const element = slot?.parent
  return (
    slot?.kind === ts.SyntaxKind.JsxExpression &&
    element?.kind === ts.SyntaxKind.JsxElement &&
    element.openingElement.tagName.getText() === "style"
  )
}

function isMarkedCssTemplate(template) {
  let node = template
  while (
    node.parent &&
    (ts.isParenthesizedExpression(node.parent) ||
      ts.isAsExpression(node.parent) ||
      ts.isSatisfiesExpression(node.parent))
  )
    node = node.parent
  const parent = node.parent
  if (
    parent?.kind === ts.SyntaxKind.TaggedTemplateExpression &&
    parent.tag.getText() === "css"
  )
    return true
  const name = parent ? bindingName(parent) : null
  if (name !== null && parent.initializer === node)
    return CSS_MARKED_NAME.test(name)
  return isStyleElementChild(node)
}

export function cssTemplates(file, text) {
  const sourceFile = parseSource(file, text)
  const found = []
  const visit = (node) => {
    if (
      (node.kind === ts.SyntaxKind.NoSubstitutionTemplateLiteral ||
        node.kind === ts.SyntaxKind.TemplateExpression) &&
      isMarkedCssTemplate(node)
    )
      found.push(templatePieces(node, sourceFile))
    ts.forEachChild(node, visit)
  }
  visit(sourceFile)
  return found
}

function parseSource(file, text) {
  return ts.createSourceFile(
    file,
    text,
    ts.ScriptTarget.Latest,
    true,
    scriptKind(file)
  )
}

export function findSourceComments(file, text) {
  const sourceFile = parseSource(file, text)
  const seen = new Map()
  const jsxTexts = []
  const collect = (ranges) => {
    for (const range of ranges ?? []) seen.set(range.pos, range)
  }
  const walk = (node) => {
    if (node.kind === ts.SyntaxKind.JsxText) {
      jsxTexts.push([node.pos, node.end])
      return
    }
    collect(ts.getLeadingCommentRanges(text, node.pos))
    collect(ts.getTrailingCommentRanges(text, node.end))
    for (const child of node.getChildren(sourceFile)) walk(child)
  }
  walk(sourceFile)
  const insideJsxText = (range) =>
    jsxTexts.some(([start, end]) => start <= range.pos && range.pos < end)
  const comments = [...seen.values()]
    .filter((range) => !insideJsxText(range))
    .map((range) => makeComment(text, range.pos, range.end))
  for (const pieces of cssTemplates(file, text)) {
    comments.push(...findCssCommentsAcross(text, pieces))
  }
  return comments.sort((a, b) => a.pos - b.pos)
}

export function findCssComments(text, from = 0, to = text.length) {
  return findCssCommentsAcross(text, [{ start: from, end: to }])
}

export function findCssCommentsAcross(text, pieces) {
  const found = []
  let quote = null
  let inUrl = false
  for (const { start, end: to } of pieces) {
    for (let i = start; i < to; i++) {
      const char = text[i]
      if (quote) {
        if (char === "\\") i++
        else if (char === quote || char === "\n") quote = null
      } else if (inUrl) {
        if (char === ")") inUrl = false
      } else if (char === '"' || char === "'") {
        quote = char
      } else if (
        /^url\(\s*[^\s"')]/i.test(text.slice(i, Math.min(i + 12, to)))
      ) {
        inUrl = true
        i = text.indexOf("(", i)
      } else if (char === "/" && text[i + 1] === "*") {
        const close = text.indexOf("*/", i + 2)
        const end = close === -1 || close + 2 > to ? to : close + 2
        found.push(makeComment(text, i, end))
        i = end - 1
      }
    }
  }
  return found
}

export function isExcluded(file, text) {
  const firstLine = text.split("\n", 1)[0]
  return EXCLUDED.some((rule) =>
    rule.path ? rule.path.test(file) : rule.first.test(firstLine)
  )
}

export function bannedComments(file, text) {
  if (isExcluded(file, text)) return []
  const comments = CSS_FILE.test(file)
    ? findCssComments(text)
    : findSourceComments(file, text)
  return comments.filter((comment) => !isDirective(comment.raw))
}

export function listFiles() {
  return execFileSync(
    "git",
    ["ls-files", "--cached", "--others", "--exclude-standard"],
    { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }
  )
    .split("\n")
    .filter((file) => SOURCE_FILE.test(file) || CSS_FILE.test(file))
    .sort()
}

export function scanFiles(files, read) {
  const found = {}
  for (const file of files) {
    const text = read(file)
    if (text === null) continue
    const banned = bannedComments(file, text)
    if (banned.length > 0) found[file] = banned
  }
  return found
}

export const countLines = (comments) =>
  comments.reduce((sum, comment) => sum + comment.lines, 0)

export function compare(found, baseline) {
  const problems = []
  const files = new Set([...Object.keys(found), ...Object.keys(baseline)])
  for (const file of [...files].sort()) {
    const comments = found[file] ?? []
    const now = countLines(comments)
    const allowed = baseline[file] ?? 0
    if (now > allowed) {
      const where = comments
        .slice(0, 10)
        .map((comment) => `${file}:${comment.line}`)
        .join(", ")
      problems.push(
        `${where}: ${now} comment lines, baseline allows ${allowed}. ${REFUSAL}`
      )
    } else if (now < allowed) {
      problems.push(
        `${file}:1: ${now} comment lines, baseline says ${allowed}. The baseline is stale. Run node scripts/no-comments.mjs --write-baseline. ${REFUSAL}`
      )
    }
  }
  return problems
}

export function nextBaseline(found, previous) {
  const next = {}
  for (const file of Object.keys(found).sort()) {
    const now = countLines(found[file])
    if (previous && now > (previous[file] ?? 0)) {
      throw new Error(
        `${file} has ${now} comment lines, baseline allows ${previous[file] ?? 0}. The baseline only shrinks. ${REFUSAL}`
      )
    }
    next[file] = now
  }
  return next
}

export function readBaseline(baselineFile = path.join(root, BASELINE_PATH)) {
  if (!existsSync(baselineFile)) return null
  return JSON.parse(readFileSync(baselineFile, "utf8"))
}

export function serializeBaseline(baseline) {
  const sorted = Object.fromEntries(Object.entries(baseline).sort())
  return `${JSON.stringify(sorted, null, 2)}\n`
}

export function readFromDisk(file) {
  const full = path.join(root, file)
  return existsSync(full) ? readFileSync(full, "utf8") : null
}

export function check() {
  const baseline = readBaseline()
  if (!baseline) {
    return [
      `${BASELINE_PATH} is missing. Run node scripts/no-comments.mjs --write-baseline. ${REFUSAL}`,
    ]
  }
  return compare(scanFiles(listFiles(), readFromDisk), baseline)
}

export function writeBaseline(baselineFile = path.join(root, BASELINE_PATH)) {
  const found = scanFiles(listFiles(), readFromDisk)
  const next = nextBaseline(found, readBaseline(baselineFile))
  writeFileSync(baselineFile, serializeBaseline(next))
  return next
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--write-baseline")) {
    try {
      const next = writeBaseline()
      const total = Object.values(next).reduce((sum, n) => sum + n, 0)
      console.log(
        `${BASELINE_PATH}: ${Object.keys(next).length} files, ${total} comment lines`
      )
    } catch (error) {
      console.error(error.message)
      process.exit(1)
    }
  } else {
    const problems = check()
    for (const problem of problems) console.error(problem)
    process.exit(problems.length === 0 ? 0 : 1)
  }
}
