import assert from "node:assert/strict"
import { execFileSync } from "node:child_process"
import { existsSync } from "node:fs"
import path from "node:path"
import { test } from "node:test"
import {
  REFUSAL,
  bannedComments,
  check,
  commentProblems,
  countLines,
  detect,
  findSourceComments,
  root,
  scanFiles,
} from "./no-comments.mjs"

const banned = (file, text) => bannedComments(file, text).map((c) => c.line)
const LIST = "scripts/no-comments.baseline.json"

test("the repo has no comment", () => {
  assert.deepEqual(check(), [])
})

test("the exceptions list file is gone", () => {
  assert.equal(existsSync(path.join(root, LIST)), false)
})

test("a line comment, a block comment and a JSDoc block each fail", () => {
  assert.deepEqual(banned("a.ts", "const a = 1\n// why\n"), [2])
  assert.deepEqual(banned("a.ts", "const a = 1 /* why */\n"), [1])
  assert.deepEqual(
    banned("a.mjs", "/**\n * why\n */\nexport const a = 1\n"),
    [1]
  )
  assert.deepEqual(banned("a.tsx", "const a = 1 // trailing\n"), [1])
  assert.deepEqual(banned("a.tsx", "const a = <b>{/* why */}</b>\n"), [1])
})

test("a block comment counts every line it spans", () => {
  const [comment] = bannedComments("a.ts", "/*\none\ntwo\n*/\n")
  assert.equal(comment.lines, 4)
  assert.equal(countLines([comment]), 4)
})

test("slashes inside strings, templates, regexes, JSX text and URLs are not comments", () => {
  const text = [
    'const url = "https://example.com/a"',
    "const single = 'a // b'",
    "const block = `x /* y */ ${1 + 1} // z`",
    "const nested = `a ${`b // c`} d`",
    "const pattern = /\\/\\/ not a comment/",
    "const slashes = /https?:\\/\\//",
    "const view = <p>see // docs and /* this */</p>",
    "",
  ].join("\n")
  assert.deepEqual(banned("a.tsx", text), [])
})

test("tool directives pass", () => {
  const text = [
    "#!/usr/bin/env node",
    "// @vitest-environment jsdom",
    '/// <reference types="vite/client" />',
    "// prettier-ignore",
    "// @ts-expect-error the fixture breaks the type on purpose",
    "// eslint-disable-next-line no-console -- the script prints its result",
    "/* eslint-disable no-console -- the script prints its result */",
    "// eslint-enable no-console",
    "const a = 1",
    "",
  ].join("\n")
  assert.deepEqual(banned("a.ts", text), [])
})

test("an eslint-disable with no reason, @ts-ignore and a mixed comment fail", () => {
  assert.deepEqual(
    banned("a.ts", "// eslint-disable-next-line no-console\n"),
    [1]
  )
  assert.deepEqual(banned("a.ts", "// @ts-ignore\nconst a = 1\n"), [1])
  assert.deepEqual(banned("a.ts", "// note: @ts-expect-error later\n"), [1])
})

test("a CSS comment fails and a CSS string with comment marks passes", () => {
  assert.deepEqual(banned("a.css", "a { color: red; }\n/* why */\n"), [2])
  assert.deepEqual(
    banned(
      "a.css",
      'a::before { content: "/* not */"; background: url(//x.test/a.png); }\n'
    ),
    []
  )
})

test("a generated file and a declaration file are skipped", () => {
  const header =
    "// Generated by scripts/pen-art-to-svg.mjs from opencv.pen node UfIKe. Do not edit by hand.\n"
  assert.deepEqual(banned("art.tsx", `${header}export const a = 1\n`), [])
  assert.deepEqual(banned("types.d.ts", "// emitted\n"), [])
  assert.deepEqual(banned("art.tsx", "// Generated by hand\n"), [1])
})

test("a comment fails with file and line", () => {
  const found = scanFiles(["src/a.ts"], () => "const a = 1\n// why\n")
  const [problem] = commentProblems(found)
  assert.match(problem, /^src\/a\.ts:2: 1 comment lines\./)
  assert.ok(problem.includes(REFUSAL))
  assert.equal(problem.includes("baseline"), false)
})

test("MISTAKE: a comment fires and clean code stays quiet", () => {
  assert.deepEqual(
    detect("const a = 1\n// why\n", "a.ts").map((comment) => comment.line),
    [2]
  )
  assert.deepEqual(detect("const a = 1\n", "a.ts"), [])
})

test("writing an exceptions list is refused", () => {
  let stderr = ""
  try {
    execFileSync(
      process.execPath,
      [path.join(root, "scripts/no-comments.mjs"), "--write-baseline"],
      { cwd: root, encoding: "utf8", timeout: 10_000 }
    )
    assert.fail("the old flag wrote a list")
  } catch (error) {
    if (error?.code === "ERR_ASSERTION") throw error
    stderr = `${error.stderr ?? ""}`
  }
  assert.match(stderr, /no exceptions list/)
  assert.equal(existsSync(path.join(root, LIST)), false)
})

test("JSX text that starts with two slashes is text, not a comment", () => {
  assert.deepEqual(banned("a.tsx", "const a = <p>// x</p>\n"), [])
  assert.deepEqual(
    banned(
      "a.tsx",
      ["const a = (", "  <p>", "    // looks like one", "  </p>", ")", ""].join(
        "\n"
      )
    ),
    []
  )
  assert.deepEqual(banned("a.tsx", "const a = <p>{/* real */}</p>\n"), [1])
})

test("a comment inside CSS in a template literal fails, mapped to its own line", () => {
  const tagged = [
    "const a = css`",
    "  a { color: red; }",
    "  /* why */",
    "`",
    "",
  ]
  assert.deepEqual(banned("a.ts", tagged.join("\n")), [3])
  const untagged = [
    "export const styles = `",
    ".a {",
    "  color: red; /* why */",
    "}",
    "`",
    "",
  ]
  assert.deepEqual(banned("a.ts", untagged.join("\n")), [3])
  const withHole = ["const bStyles = `.a { width: ${w}px; /* why */ }`", ""]
  assert.deepEqual(banned("a.ts", withHole.join("\n")), [1])
})

test("a template that is not CSS keeps its comment marks, and CSS strings keep theirs", () => {
  assert.deepEqual(banned("a.ts", "const a = `see /* x */ and { a: b }`\n"), [])
  assert.deepEqual(banned("a.ts", "const a = `a /* x */ b`\n"), [])
  const quoted = ['const a = `.a { content: "/* q */"; color: red; }`', ""]
  assert.deepEqual(banned("a.ts", quoted.join("\n")), [])
})

test("MISTAKE: a CSS string after a hole keeps its /* mark, and a real comment after it goes", () => {
  const source = [
    "const css = `.a { content: '${x} /* keep */'; /* drop */ color: red; }`",
    "",
  ]
  const found = banned("a.ts", source.join("\n"))
  assert.deepEqual(found, [1])
  assert.equal(
    findSourceComments("a.ts", source.join("\n"))
      .map((c) => c.raw)
      .join(),
    "/* drop */"
  )
})

test("MISTAKE: a template that looks like CSS but is not marked keeps every comment mark", () => {
  const samples = [
    "const sample = `function f() { return a ? b : c; } /* note */`\n",
    "const md = `Use { color: red; } then /* not css */ text`\n",
    "const a = f(`.a { color: red; /* x */ }`)\n",
    "const b = `.a { color: red; /* x */ }`\n",
  ]
  for (const source of samples) assert.deepEqual(banned("a.ts", source), [])
})

test("a template is CSS when tagged css, named css or *Styles, or the child of a style element", () => {
  const marked = [
    "const a = css`.a { color: red; } /* x */`\n",
    "const css = `.a { color: red; } /* x */`\n",
    "const cardStyles = `.a { color: red; } /* x */`\n",
    "const o = { styles: `.a { color: red; } /* x */` }\n",
    "const a = <style>{`.a { color: red; } /* x */`}</style>\n",
  ]
  for (const source of marked) {
    const file = source.includes("<style") ? "a.tsx" : "a.ts"
    assert.deepEqual(banned(file, source), [1], source)
  }
})

test("an unquoted url( in CSS is one token, so its /* is kept", () => {
  assert.deepEqual(
    banned("a.ts", "const css = `.a { background: url(x/*y*/z); }`\n"),
    []
  )
})
