import assert from "node:assert/strict"
import { readFileSync, rmSync, writeFileSync } from "node:fs"
import path from "node:path"
import { test } from "node:test"
import {
  BASELINE_PATH,
  REFUSAL,
  bannedComments,
  check,
  compare,
  countLines,
  nextBaseline,
  readBaseline,
  root,
  scanFiles,
  serializeBaseline,
} from "./no-comments.mjs"
import { makeTempDir } from "./lib/temp-dir.mjs"

const banned = (file, text) => bannedComments(file, text).map((c) => c.line)

test("the repo adds no comment beyond the shrink-only baseline", () => {
  assert.deepEqual(check(), [])
})

test("the committed baseline stays under the file size limit", () => {
  const size = readFileSync(path.join(root, BASELINE_PATH)).length
  assert.ok(size < 20000, `${BASELINE_PATH} is ${size} bytes`)
})

test("a line comment, a block comment and a JSDoc block each fail", () => {
  assert.deepEqual(banned("a.ts", "const a = 1\n// why\n"), [2])
  assert.deepEqual(banned("a.ts", "const a = 1 /* why */\n"), [1])
  assert.deepEqual(
    banned("a.mjs", "/**\n * why\n */\nexport const a = 1\n"),
    [1]
  )
  assert.deepEqual(banned("a.tsx", "const a = 1 // trailing\n"), [1])
  assert.deepEqual(banned("a.tsx", "const a = <b>{/* why */}</b>\n"), [1])
})

test("a block comment counts every line it spans", () => {
  const [comment] = bannedComments("a.ts", "/*\none\ntwo\n*/\n")
  assert.equal(comment.lines, 4)
  assert.equal(countLines([comment]), 4)
})

test("slashes inside strings, templates, regexes, JSX text and URLs are not comments", () => {
  const text = [
    'const url = "https://example.com/a"',
    "const single = 'a // b'",
    "const block = `x /* y */ ${1 + 1} // z`",
    "const nested = `a ${`b // c`} d`",
    "const pattern = /\\/\\/ not a comment/",
    "const slashes = /https?:\\/\\//",
    "const view = <p>see // docs and /* this */</p>",
    "",
  ].join("\n")
  assert.deepEqual(banned("a.tsx", text), [])
})

test("tool directives pass", () => {
  const text = [
    "#!/usr/bin/env node",
    "// @vitest-environment jsdom",
    '/// <reference types="vite/client" />',
    "// prettier-ignore",
    "// @ts-expect-error the fixture breaks the type on purpose",
    "// eslint-disable-next-line no-console -- the script prints its result",
    "/* eslint-disable no-console -- the script prints its result */",
    "// eslint-enable no-console",
    "const a = 1",
    "",
  ].join("\n")
  assert.deepEqual(banned("a.ts", text), [])
})

test("an eslint-disable with no reason, @ts-ignore and a mixed comment fail", () => {
  assert.deepEqual(
    banned("a.ts", "// eslint-disable-next-line no-console\n"),
    [1]
  )
  assert.deepEqual(banned("a.ts", "// @ts-ignore\nconst a = 1\n"), [1])
  assert.deepEqual(banned("a.ts", "// note: @ts-expect-error later\n"), [1])
})

test("a CSS comment fails and a CSS string with comment marks passes", () => {
  assert.deepEqual(banned("a.css", "a { color: red; }\n/* why */\n"), [2])
  assert.deepEqual(
    banned(
      "a.css",
      'a::before { content: "/* not */"; background: url(//x.test/a.png); }\n'
    ),
    []
  )
})

test("a generated file and a declaration file are skipped", () => {
  const header =
    "// Generated by scripts/pen-art-to-svg.mjs from opencv.pen node UfIKe. Do not edit by hand.\n"
  assert.deepEqual(banned("art.tsx", `${header}export const a = 1\n`), [])
  assert.deepEqual(banned("types.d.ts", "// emitted\n"), [])
  assert.deepEqual(banned("art.tsx", "// Generated by hand\n"), [1])
})

test("a new comment in a file with no baseline entry fails with file:line", () => {
  const found = scanFiles(["src/a.ts"], () => "const a = 1\n// why\n")
  const [problem] = compare(found, {})
  assert.match(problem, /^src\/a\.ts:2: 1 comment lines, baseline allows 0\./)
  assert.ok(problem.includes(REFUSAL))
})

test("more comments than the baseline allows fail", () => {
  const found = scanFiles(["src/a.ts"], () => "// one\n// two\n")
  const [problem] = compare(found, { "src/a.ts": 1 })
  assert.match(problem, /src\/a\.ts:1.*2 comment lines, baseline allows 1/)
})

test("fewer comments than the baseline is a stale baseline", () => {
  const found = scanFiles(["src/a.ts"], () => "// one\n")
  const [problem] = compare(found, { "src/a.ts": 2 })
  assert.match(problem, /baseline is stale.*--write-baseline/)
  assert.ok(problem.includes(REFUSAL))
})

test("a baseline entry for a file that is gone is stale", () => {
  const [problem] = compare({}, { "src/gone.ts": 3 })
  assert.match(problem, /^src\/gone\.ts:1: 0 comment lines, baseline says 3\./)
})

test("a matching baseline passes", () => {
  const found = scanFiles(["src/a.ts"], () => "// one\n")
  assert.deepEqual(compare(found, { "src/a.ts": 1 }), [])
})

test("writing the baseline refuses to raise a count or add a file", () => {
  const raised = scanFiles(["src/a.ts"], () => "// one\n// two\n")
  assert.throws(() => nextBaseline(raised, { "src/a.ts": 1 }), /only shrinks/)
  assert.throws(() => nextBaseline(raised, {}), /only shrinks/)
})

test("writing the baseline lowers counts and drops files that are clean", () => {
  const found = scanFiles(["src/a.ts", "src/b.ts"], (file) =>
    file === "src/a.ts" ? "// one\n" : "const b = 1\n"
  )
  assert.deepEqual(nextBaseline(found, { "src/a.ts": 3, "src/b.ts": 2 }), {
    "src/a.ts": 1,
  })
})

test("the baseline file round-trips through disk in sorted order", () => {
  const dir = makeTempDir("no-comments-")
  try {
    const file = path.join(dir, "baseline.json")
    assert.equal(readBaseline(file), null)
    writeFileSync(file, serializeBaseline({ "b.ts": 1, "a.ts": 2 }))
    assert.deepEqual(Object.keys(readBaseline(file)), ["a.ts", "b.ts"])
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
})
