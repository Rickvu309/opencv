const HERE = dirname(fileURLToPath(import.meta.url))
const LIMIT = 19000

if (translateWorld(12, -3, 5) !== k.translateAlong(P, [12, -3, 5])) {
  throw new Error("camera helper drifted from iso-kit")
}

function pack(groups) {
  const entries = []
  for (const [name, pieces] of groups) {
    let buffer = ""
    let index = 0
    const flush = () => {
      if (!buffer) return
      entries.push([`${name}_${index}`, buffer])
      buffer = ""
      index += 1
    }
    for (const piece of pieces) {
      if (buffer && (buffer + piece).length > 15000) flush()
      buffer += piece
    }
    flush()
  }
  return entries
}

function emit(folder, prefix, scene, moveKeys) {
  const dir = join(HERE, folder)
  mkdirSync(dir, { recursive: true })
  const groups = [
    ["back", scene.layers.back],
    ["cover", scene.layers.cover],
    ["near", scene.layers.near],
    ...moveKeys.map((key) => [key.replaceAll("-", "_"), [scene.moves[key]]]),
  ]
  const entries = pack(groups).map(([name, svg]) => {
    const body = `export const ${prefix}_${name} = ${JSON.stringify(svg)}\n`
    if (body.length > LIMIT)
      throw new Error(`${prefix}_${name} is ${body.length} bytes`)
    return [name, body]
  })
  const files = []
  let bucket = []
  let size = 80
  const flush = () => {
    if (!bucket.length) return
    const file = `part-${files.length}.ts`
    const text = `// Generated by figures/generate.mjs. Re-run that script; do not edit.\n${bucket.map((item) => item[1]).join("")}`
    if (text.length > 20000)
      throw new Error(`${folder}/${file} is ${text.length}`)
    writeFileSync(join(dir, file), text)
    files.push({ file, names: bucket.map((item) => item[0]) })
    bucket = []
    size = 80
  }
  for (const entry of entries) {
    if (bucket.length && size + entry[1].length > LIMIT) flush()
    bucket.push(entry)
    size += entry[1].length
  }
  flush()
  const exported = files.flatMap((file) => file.names)
  const layers = [
    "back",
    "cover",
    "near",
    ...moveKeys.map((key) => key.replaceAll("-", "_")),
  ]
  const bindings = layers.map((layer) => {
    const pieces = exported.filter(
      (name) => name === layer || name.startsWith(`${layer}_`)
    )
    return `export const ${layer} = [${pieces.map((name) => `${prefix}_${name}`).join(", ")}] as const`
  })
  const imports = files
    .map(
      (file) =>
        `import { ${file.names.map((name) => `${prefix}_${name}`).join(", ")} } from "./${file.file}"`
    )
    .join("\n")
  const barrel = `// Generated by figures/generate.mjs. Re-run that script; do not edit.\n${imports}\n\n${bindings.join("\n")}\n\nexport const PART_COUNT = ${scene.names.size}\n`
  if (barrel.length > 20000)
    throw new Error(`${prefix} barrel is ${barrel.length}`)
  writeFileSync(join(dir, "geometry.ts"), barrel)
  return files.length
}

function build(name, builder, moves) {
  const scene = createScene()
  builder(scene)
  if (scene.names.size < 40 || scene.names.size > 80)
    throw new Error(`${name} has ${scene.names.size} parts`)
  for (const part of moves) {
    if (!scene.moves[part]) throw new Error(`${name} missing ${part}`)
  }
  return scene
}

const proof = build("proof", buildProof, ["platen", "pin-0", "pin-1", "pin-2"])
const plotter = build("plotter", buildPlotter, ["carriage"])
const dispatch = build("dispatch", buildDispatch, ["carriage"])
const files = {
  proof: emit("proof", "PROOF", proof, ["platen", "pin-0", "pin-1", "pin-2"]),
  plotter: emit("plotter", "PLOTTER", plotter, ["carriage"]),
  dispatch: emit("dispatch", "DISPATCH", dispatch, ["carriage"]),
}

